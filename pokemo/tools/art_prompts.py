def tiles_prompt(theme,cells):
    lines=[f"用同樣的風格畫一張「地圖地磚圖集」，主題：{theme}。",
      "- 正方形 1024×1024，平均切成 4 欄 × 4 列共 16 格，每格 256×256；格子之間不要留縫、不要格線、不要編號",
      "- 每一格都是從正上方往下看的地面材質，整格填滿，而且要能無縫重複拼接（上下左右接起來看不出接縫）",
      "- 這張不要洋紅背景",
      "各格內容（由左到右、由上到下）："]
    for r in range(4):
        lines.append(f"第 {r+1} 列："+"　".join(f"{'①②③④⑤⑥⑦⑧⑨⑩⑪⑫⑬⑭⑮⑯'[r*4+i]}{cells[r*4+i]}" for i in range(4)))
    return "\n".join(lines)

def objects_prompt(theme,items):
    lines=[f"用同樣的風格畫一張「地圖物件」合集，主題：{theme}。",
      "- 正方形 1024×1024，純洋紅 #FF00FF 背景",
      "- 平均分成 3 欄 × 3 列，每格放一個物件；物件置中、完整不被裁切，彼此不要重疊或相連，四周留洋紅空白",
      "- 物件是俯視約 45 度斜角的立體造型，底部只有一點地面陰影；不要加底座、小島、石台或一圈草地",
      "各格（由左到右、由上到下）："]
    lines+= [f"{i+1}. {t}" for i,t in enumerate(items)]
    return "\n".join(lines)

